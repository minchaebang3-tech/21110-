# → 줄 앞 공백과 빈 줄을 지워서
#   HTML이 코드 블록으로 오인되어 화면에 그대로 뜨는 문제를 막음
# ============================================================
def show_html(body):

    body = "\n".join(
        line.strip()
        for line in body.split("\n")
        if line.strip()
    )

    st.markdown(
        body,
        unsafe_allow_html=True
    )


